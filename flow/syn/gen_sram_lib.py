#!/usr/bin/env python3
"""Writes syn/lib/sram_macros.lib: timing models for the SRAM black boxes of
rtl/mem/sram_macros.sv, so STA can time the paths into and out of the
memories. The numbers are assumptions, the same at every corner, not a
characterized or generated SRAM (docs/09_timing.md):

  clock to Q     3.0 ns      setup 0.8 ns      hold 0.2 ns
  input pin capacitance 0.005 pF, clock pin 0.010 pF, output transition 0.2 ns

Usage: python3 flow/syn/gen_sram_lib.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "syn/lib/sram_macros.lib"

CLK_Q, SETUP, HOLD = 3.0, 0.8, 0.2
CAP_IN, CAP_CLK, TRAN = 0.005, 0.010, 0.2
MACROS = [("sram_2048x64", 11), ("sram_8192x64", 13), ("sram_512x64", 9)]


def constraint(kind, value):
    return (f"      timing () {{\n"
            f"        related_pin : \"CLK\";\n"
            f"        timing_type : {kind};\n"
            f"        rise_constraint (scalar) {{ values (\"{value}\"); }}\n"
            f"        fall_constraint (scalar) {{ values (\"{value}\"); }}\n"
            f"      }}\n")


def in_bus(name, width):
    return (f"    bus ({name}) {{\n"
            f"      bus_type : bus{width};\n"
            f"      direction : input;\n"
            f"      capacitance : {CAP_IN};\n"
            + constraint("setup_rising", SETUP) + constraint("hold_rising", HOLD) +
            f"    }}\n")


def in_pin(name):
    return (f"    pin ({name}) {{\n"
            f"      direction : input;\n"
            f"      capacitance : {CAP_IN};\n"
            + constraint("setup_rising", SETUP) + constraint("hold_rising", HOLD) +
            f"    }}\n")


def main():
    widths = sorted({8, 64} | {a for _, a in MACROS})
    s = []
    s.append("/* Generated by flow/syn/gen_sram_lib.py: assumed timing for the SRAM black\n"
             "   boxes (docs/09_timing.md). Not a characterized SRAM. */\n")
    s.append("library (sram_macros) {\n"
             "  delay_model : table_lookup;\n"
             "  time_unit : \"1ns\";\n"
             "  voltage_unit : \"1V\";\n"
             "  current_unit : \"1mA\";\n"
             "  pulling_resistance_unit : \"1kohm\";\n"
             "  leakage_power_unit : \"1nW\";\n"
             "  capacitive_load_unit (1, pf);\n"
             "  nom_process : 1.0;\n"
             "  nom_voltage : 1.8;\n"
             "  nom_temperature : 25.0;\n"
             "  input_threshold_pct_rise : 50;\n"
             "  input_threshold_pct_fall : 50;\n"
             "  output_threshold_pct_rise : 50;\n"
             "  output_threshold_pct_fall : 50;\n"
             "  slew_lower_threshold_pct_rise : 20;\n"
             "  slew_lower_threshold_pct_fall : 20;\n"
             "  slew_upper_threshold_pct_rise : 80;\n"
             "  slew_upper_threshold_pct_fall : 80;\n")
    for w in widths:
        s.append(f"  type (bus{w}) {{\n"
                 f"    base_type : array;\n"
                 f"    data_type : bit;\n"
                 f"    bit_width : {w};\n"
                 f"    bit_from : {w - 1};\n"
                 f"    bit_to : 0;\n"
                 f"    downto : true;\n"
                 f"  }}\n")
    for name, aw in MACROS:
        s.append(f"  cell ({name}) {{\n"
                 f"    area : 0;\n"
                 f"    dont_touch : true;\n"
                 f"    dont_use : true;\n"
                 f"    pin (CLK) {{\n"
                 f"      direction : input;\n"
                 f"      clock : true;\n"
                 f"      capacitance : {CAP_CLK};\n"
                 f"    }}\n")
        s.append(in_bus("WE", 8))
        s.append(in_bus("WA", aw))
        s.append(in_bus("D", 64))
        s.append(in_pin("RE"))
        s.append(in_bus("RA", aw))
        s.append(f"    bus (Q) {{\n"
                 f"      bus_type : bus64;\n"
                 f"      direction : output;\n"
                 f"      timing () {{\n"
                 f"        related_pin : \"CLK\";\n"
                 f"        timing_type : rising_edge;\n"
                 f"        timing_sense : non_unate;\n"
                 f"        cell_rise (scalar) {{ values (\"{CLK_Q}\"); }}\n"
                 f"        cell_fall (scalar) {{ values (\"{CLK_Q}\"); }}\n"
                 f"        rise_transition (scalar) {{ values (\"{TRAN}\"); }}\n"
                 f"        fall_transition (scalar) {{ values (\"{TRAN}\"); }}\n"
                 f"      }}\n"
                 f"    }}\n"
                 f"  }}\n")
    s.append("}\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("".join(s))
    print(f"[SYN] {OUT.relative_to(ROOT)}: {len(MACROS)} macros")


if __name__ == "__main__":
    main()
